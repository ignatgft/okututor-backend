package com.okututor.backend.media;

/** стратегия кадрирования при приведении к целевым размерам. */
public enum CropMode {
    /** центральный квадратный crop (аватары). */
    CENTER_SQUARE,
    /** центральный crop под целевое соотношение сторон 16:9 (обложки курсов). */
    CENTER_ASPECT,
    /** вписать в рамку без искажений, без увеличения маленьких (profile image). */
    FIT
}
